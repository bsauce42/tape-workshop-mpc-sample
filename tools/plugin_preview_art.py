"""Embed the checked-in 160x120 UI screenshots for the plug-in picker."""
import base64
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
items = json.loads((root / 'tools/workshop_plugins.json').read_text())['bundles']
text = '// SPDX-License-Identifier: AGPL-3.0-only\n// Tape Workshop UI screenshots, embedded so browsing never loads a plug-in.\n// Generated by tools/plugin_preview_art.py.\n#pragma once\nnamespace melodee {\nstruct PluginPreviewArt { const char* name; const char* library; const char* png; };\ninline constexpr PluginPreviewArt plugin_preview_art[] {\n'
for item in items:
    name = item['folder'].split(' - VST - ')[-1]
    image = root / 'src/melodee/ui/plugin_previews' / (name.replace(' ', '-') + '.png')
    if not image.exists():
        print('No custom preview for ' + name + '; the browser uses its fallback card.')
        continue
    data = base64.b64encode(image.read_bytes()).decode()
    text += '    {"' + name + '", "' + item['libraries'][0] + '",\n'
    text += ''.join('        "' + data[i:i+100] + '"\n' for i in range(0, len(data), 100)) + '    },\n'
text += '};\n}\n'
(root / 'src/melodee/ui/plugin_preview_art.h').write_text(text)
